/// `command` with its row applied; one with no row stays `Denied`.
pub fn classified<C>(command: Command<C>) -> Command<C> {
    match TABLE.iter().find(|(id, ..)| *id == command.id) {
        Some(&(_, policy, effect)) => command.automation(policy, effect),
        None => command,
    }
}
